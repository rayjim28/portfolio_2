#!/usr/bin/env python3
"""Conservative Pages Router SEO/accessibility patch; does not change portfolio layout."""
import argparse
from html import escape
from pathlib import Path
import re
import sys
from urllib.parse import urlparse
SEO_START='{/* PORTFOLIO FINAL SEO START */}'
SEO_END='{/* PORTFOLIO FINAL SEO END */}'
CSS_START='/* PORTFOLIO ACCESSIBILITY POLISH START */'
CSS_END='/* PORTFOLIO ACCESSIBILITY POLISH END */'
CSS_BLOCK='''/* PORTFOLIO ACCESSIBILITY POLISH START */
.skip-to-main {
  position: fixed;
  z-index: 10000;
  top: -200px;
  left: 16px;
  padding: 12px 18px;
  border: 2px solid var(--blue);
  border-radius: 8px;
  background: var(--panel);
  color: var(--text);
  font-weight: 700;
}
.skip-to-main:focus-visible {
  top: 12px;
  outline: 3px solid var(--blue);
  outline-offset: 2px;
}
@media (prefers-reduced-motion: reduce) {
  html { scroll-behavior: auto !important; }
}
/* PORTFOLIO ACCESSIBILITY POLISH END */'''

def apply(root, site_url=None):
    page=root/'src/pages/index.tsx'
    style=root/'src/styles/globals.css'
    if not page.is_file() or not style.is_file():
        raise ValueError('Run from the portfolio_2 project root (index.tsx or globals.css missing).')
    before=page.read_text(encoding='utf-8')
    css_before=style.read_text(encoding='utf-8')
    if '<Head>' not in before or '</Head>' not in before or '<div className="site-shell">' not in before:
        raise ValueError('Expected Next.js page structure missing; no changes made.')
    if '<main>' not in before and '<main id="main-content">' not in before:
        raise ValueError('Main content element not found; no changes made.')
    if SEO_START not in before and ('property="og:title"' in before or 'name="twitter:card"' in before):
        raise ValueError('Existing social metadata needs review; no changes made.')
    desc='Software engineering projects by Raymond Jimenez: full-stack apps, APIs, databases and network diagnostics.'
    items=[
      '<meta property="og:type" content="website" />',
      '<meta property="og:title" content="Raymond Jimenez | Software Engineer" />',
      f'<meta property="og:description" content="{desc}" />',
      '<meta property="og:locale" content="en_US" />',
      '<meta name="twitter:title" content="Raymond Jimenez | Software Engineer" />',
      f'<meta name="twitter:description" content="{desc}" />',
    ]
    if site_url:
        items.insert(0, f'<link rel="canonical" href="{escape(site_url,quote=True)}/" />')
        items.append(f'<meta property="og:url" content="{escape(site_url,quote=True)}/" />')
    if site_url and (root/'public/screenshot-of-portfolio.png').is_file():
        items.extend([
          f'<meta property="og:image" content="{escape(site_url,quote=True)}/screenshot-of-portfolio.png" />',
          '<meta property="og:image:alt" content="Raymond Jimenez portfolio preview" />',
          '<meta name="twitter:card" content="summary_large_image" />',
        ])
    else:
        items.append('<meta name="twitter:card" content="summary" />')
    block='\n        '+SEO_START+'\n        '+'\n        '.join(items)+'\n        '+SEO_END+'\n'
    if SEO_START in before:
        updated=re.sub(r'\s*'+re.escape(SEO_START)+r'.*?'+re.escape(SEO_END)+r'\s*',block,before,count=1,flags=re.DOTALL)
    else:
        updated=before.replace('<Head>','<Head>'+block,1)
    if 'className="skip-to-main"' not in updated:
        updated=updated.replace('<div className="site-shell">',
          '<div className="site-shell">\n      <a className="skip-to-main" href="#main-content">Skip to main content</a>',1)
    if '<main id="main-content">' not in updated:
        updated=updated.replace('<main>','<main id="main-content">',1)
    if CSS_START in css_before:
        css_updated=re.sub(re.escape(CSS_START)+r'.*?'+re.escape(CSS_END),CSS_BLOCK,css_before,count=1,flags=re.DOTALL)
    else:
        css_updated=css_before.rstrip()+'\n\n'+CSS_BLOCK+'\n'
    if updated!=before:
        backup=page.with_name('index.tsx.final-polish-backup')
        if not backup.exists(): backup.write_text(before,encoding='utf-8')
        page.write_text(updated,encoding='utf-8')
    if css_updated!=css_before:
        backup=style.with_name('globals.css.final-polish-backup')
        if not backup.exists(): backup.write_text(css_before,encoding='utf-8')
        style.write_text(css_updated,encoding='utf-8')
    robots=root/'public/robots.txt'
    if not robots.exists():
        robots.parent.mkdir(parents=True,exist_ok=True)
        robots.write_text('User-agent: *\nAllow: /\n',encoding='utf-8')
    if site_url:
        sitemap=root/'public/sitemap.xml'
        if not sitemap.exists() or 'Generated by portfolio final polish' in sitemap.read_text(encoding='utf-8'):
            sitemap.write_text('<?xml version="1.0" encoding="UTF-8"?>\n<!-- Generated by portfolio final polish -->\n<urlset xmlns="http://www.sitemaps.org/schemas/sitemap/0.9">\n  <url><loc>'+escape(site_url)+'/</loc></url>\n</urlset>\n',encoding='utf-8')
    print('Applied portfolio SEO/accessibility update.')
    if not site_url:
        print('Canonical, social preview image, and sitemap skipped until actual public URL is confirmed.')
    else: print('Canonical and sitemap set to:',site_url)

def main():
    parser=argparse.ArgumentParser()
    parser.add_argument('--site-url',help='Optional verified HTTPS URL for the actual live portfolio')
    args=parser.parse_args()
    url=None
    if args.site_url:
        url=args.site_url.strip().rstrip('/')
        p=urlparse(url)
        if p.scheme!='https' or not p.netloc or p.username or p.password or p.path or p.query or p.fragment:
            parser.error('Site URL must be a public HTTPS homepage, e.g. https://example.com')
    try: apply(Path.cwd(),url)
    except ValueError as exc: sys.exit(str(exc))

if __name__=='__main__':main()
